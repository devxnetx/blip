    public static function categoryFor(string $message): string
    {
        $text = mb_strtolower($message);
        $has = fn (string $needle): bool => str_contains($text, mb_strtolower($needle));

        if ($has('търся')) {
            return 'seeking';
        }
        if ($has('безплат') || $has('раздавам') || $has('раздават') || $has('вземете') || $has('супа')) {
            return 'free';
        }
        foreach (['внимава', 'затвор', 'шахт', 'газ', 'сбиване', 'полици', 'авария', 'ремонт', 'блокир', 'мига', 'аларм', 'катастроф', 'протест', 'линейка', 'счуп', 'хлъзгав', 'наводн', 'паднал', 'паднало', 'светофар', 'тръба', 'няма ток'] as $needle) {
            if ($has($needle)) {
                return 'warning';
            }
        }
        foreach (['изгубен', 'намерих', 'ключов', 'портфейл', 'портмоне', 'котка', 'куче', 'раница', 'слушалки'] as $needle) {
            if ($has($needle)) {
                return 'lost';
            }
        }

        return 'other';
    }

    /**
     * @return array{0: float, 1: float}
     */
    private function scatter(float $lat, float $lng, int $index, int $count, float $radius): array
    {
        $angle = $index * 2.399963229728653;
        $ring = sqrt(($index + 0.5) / max(1, $count));
        $latOffset = sin($angle) * $radius * $ring;
        $lngScale = 1 / max(0.2, cos(deg2rad($lat)));
        $lngOffset = cos($angle) * $radius * $ring * $lngScale;

        return [round($lat + $latOffset, 7), round($lng + $lngOffset, 7)];
    }
